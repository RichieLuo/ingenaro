//! Original line icons on a shared 24 × 24 grid.

use super::geometry::paths;

#[derive(Clone, Copy, Debug, PartialEq)]
pub(super) enum Icon {
    Search,
    Close,
    Menu,
    Home,
    User,
    Check,
    Plus,
    Next,
    Left,
    Right,
    Down,
    Minus,
    Edit,
    Trash,
    Copy,
    Settings,
    Filter,
    Download,
    Upload,
    Folder,
    Bell,
    Calendar,
    Heart,
    Star,
    Info,
    Alert,
    Lock,
    Mail,
}

enum Ink {
    Path(&'static [[f32; 2]]),
    Circle([f32; 2], f32),
}

impl Icon {
    pub(super) fn contours(self) -> Vec<(Vec<[f32; 2]>, bool)> {
        use Ink::{Circle, Path};
        let strokes: &[Ink] = match self {
            Self::Search => &[
                Circle([10.0, 10.0], 6.0),
                Path(&[[14.25, 14.25], [20.0, 20.0]]),
            ],
            Self::Close => &[
                Path(&[[6.0, 6.0], [18.0, 18.0]]),
                Path(&[[18.0, 6.0], [6.0, 18.0]]),
            ],
            Self::Menu => &[
                Path(&[[4.0, 6.0], [20.0, 6.0]]),
                Path(&[[4.0, 12.0], [20.0, 12.0]]),
                Path(&[[4.0, 18.0], [20.0, 18.0]]),
            ],
            Self::Home => &[
                Path(&[[3.0, 11.0], [12.0, 3.0], [21.0, 11.0]]),
                Path(&[[5.5, 9.0], [5.5, 20.5], [18.5, 20.5], [18.5, 9.0]]),
                Path(&[[9.5, 20.5], [9.5, 14.0], [14.5, 14.0], [14.5, 20.5]]),
            ],
            Self::User => &[
                Circle([12.0, 7.5], 4.0),
                Path(&[
                    [4.5, 20.5],
                    [4.5, 18.0],
                    [5.5, 15.8],
                    [7.5, 14.3],
                    [16.5, 14.3],
                    [18.5, 15.8],
                    [19.5, 18.0],
                    [19.5, 20.5],
                ]),
            ],
            Self::Check => &[Path(&[[4.5, 12.0], [9.5, 17.0], [19.5, 7.0]])],
            Self::Plus => &[
                Path(&[[5.0, 12.0], [19.0, 12.0]]),
                Path(&[[12.0, 5.0], [12.0, 19.0]]),
            ],
            Self::Next => &[Path(&[[9.0, 5.5], [15.5, 12.0], [9.0, 18.5]])],
            Self::Left => &[
                Path(&[[11.0, 5.5], [4.5, 12.0], [11.0, 18.5]]),
                Path(&[[4.5, 12.0], [20.0, 12.0]]),
            ],
            Self::Right => &[
                Path(&[[13.0, 5.5], [19.5, 12.0], [13.0, 18.5]]),
                Path(&[[4.0, 12.0], [19.5, 12.0]]),
            ],
            Self::Down => &[Path(&[[5.5, 9.0], [12.0, 15.5], [18.5, 9.0]])],
            Self::Minus => &[Path(&[[5.0, 12.0], [19.0, 12.0]])],
            Self::Edit => &[
                Path(&[
                    [4.0, 20.0],
                    [5.0, 15.0],
                    [16.5, 3.5],
                    [20.5, 7.5],
                    [9.0, 19.0],
                    [4.0, 20.0],
                ]),
                Path(&[[13.75, 6.25], [17.75, 10.25]]),
            ],
            Self::Trash => &[
                Path(&[[3.5, 6.5], [20.5, 6.5]]),
                Path(&[[9.0, 6.5], [9.0, 3.5], [15.0, 3.5], [15.0, 6.5]]),
                Path(&[[6.0, 6.5], [7.0, 20.5], [17.0, 20.5], [18.0, 6.5]]),
                Path(&[[10.0, 10.0], [10.5, 17.0]]),
                Path(&[[14.0, 10.0], [13.5, 17.0]]),
            ],
            Self::Copy => &[
                Path(&[
                    [5.5, 17.0],
                    [3.5, 17.0],
                    [3.5, 3.5],
                    [16.5, 3.5],
                    [16.5, 5.5],
                ]),
                Path(&[
                    [7.5, 7.5],
                    [20.5, 7.5],
                    [20.5, 20.5],
                    [7.5, 20.5],
                    [7.5, 7.5],
                ]),
            ],
            Self::Settings => &[
                Path(&[
                    [10.0, 3.0],
                    [14.0, 3.0],
                    [14.7, 5.7],
                    [16.2, 6.5],
                    [18.8, 5.8],
                    [21.0, 9.3],
                    [19.0, 11.1],
                    [19.0, 12.9],
                    [21.0, 14.7],
                    [18.8, 18.2],
                    [16.2, 17.5],
                    [14.7, 18.3],
                    [14.0, 21.0],
                    [10.0, 21.0],
                    [9.3, 18.3],
                    [7.8, 17.5],
                    [5.2, 18.2],
                    [3.0, 14.7],
                    [5.0, 12.9],
                    [5.0, 11.1],
                    [3.0, 9.3],
                    [5.2, 5.8],
                    [7.8, 6.5],
                    [9.3, 5.7],
                    [10.0, 3.0],
                ]),
                Circle([12.0, 12.0], 3.4),
            ],
            Self::Filter => &[Path(&[
                [3.5, 5.0],
                [20.5, 5.0],
                [14.0, 12.5],
                [14.0, 18.0],
                [10.0, 20.0],
                [10.0, 12.5],
                [3.5, 5.0],
            ])],
            Self::Download | Self::Upload => &[
                Path(&[[4.0, 15.5], [4.0, 20.0], [20.0, 20.0], [20.0, 15.5]]),
                Path(&[[12.0, 3.5], [12.0, 15.5]]),
                if self == Self::Download {
                    Path(&[[7.5, 11.0], [12.0, 15.5], [16.5, 11.0]])
                } else {
                    Path(&[[7.5, 8.0], [12.0, 3.5], [16.5, 8.0]])
                },
            ],
            Self::Folder => &[Path(&[
                [3.0, 19.5],
                [3.0, 5.5],
                [10.0, 5.5],
                [12.0, 8.0],
                [21.0, 8.0],
                [21.0, 19.5],
                [3.0, 19.5],
            ])],
            Self::Bell => &[
                Path(&[
                    [4.0, 17.0],
                    [6.0, 14.0],
                    [6.0, 9.5],
                    [6.8, 7.0],
                    [9.0, 5.0],
                    [12.0, 4.3],
                    [15.0, 5.0],
                    [17.2, 7.0],
                    [18.0, 9.5],
                    [18.0, 14.0],
                    [20.0, 17.0],
                    [4.0, 17.0],
                ]),
                Path(&[[9.5, 20.0], [10.5, 21.0], [13.5, 21.0], [14.5, 20.0]]),
            ],
            Self::Calendar => &[
                Path(&[
                    [4.0, 5.5],
                    [20.0, 5.5],
                    [20.0, 20.5],
                    [4.0, 20.5],
                    [4.0, 5.5],
                ]),
                Path(&[[4.0, 10.0], [20.0, 10.0]]),
                Path(&[[8.5, 3.0], [8.5, 7.5]]),
                Path(&[[15.5, 3.0], [15.5, 7.5]]),
                Path(&[[9.0, 15.0], [11.0, 17.0], [15.0, 13.0]]),
            ],
            Self::Heart => &[Path(&[
                [12.0, 20.0],
                [5.0, 13.5],
                [3.5, 10.5],
                [3.8, 7.7],
                [5.6, 5.6],
                [8.1, 5.0],
                [10.1, 5.7],
                [12.0, 7.7],
                [13.9, 5.7],
                [15.9, 5.0],
                [18.4, 5.6],
                [20.2, 7.7],
                [20.5, 10.5],
                [19.0, 13.5],
                [12.0, 20.0],
            ])],
            Self::Star => &[Path(&[
                [12.0, 3.0],
                [14.8, 8.7],
                [21.0, 9.6],
                [16.5, 14.0],
                [17.6, 20.2],
                [12.0, 17.2],
                [6.4, 20.2],
                [7.5, 14.0],
                [3.0, 9.6],
                [9.2, 8.7],
                [12.0, 3.0],
            ])],
            Self::Info => &[
                Circle([12.0, 12.0], 8.5),
                Path(&[[12.0, 11.0], [12.0, 16.5]]),
                Path(&[[12.0, 7.6], [12.0, 8.0]]),
            ],
            Self::Alert => &[
                Path(&[[12.0, 3.5], [21.0, 20.0], [3.0, 20.0], [12.0, 3.5]]),
                Path(&[[12.0, 9.5], [12.0, 13.5]]),
                Path(&[[12.0, 16.6], [12.0, 17.0]]),
            ],
            Self::Lock => &[
                Path(&[
                    [5.0, 10.5],
                    [19.0, 10.5],
                    [19.0, 20.5],
                    [5.0, 20.5],
                    [5.0, 10.5],
                ]),
                Path(&[
                    [8.0, 10.5],
                    [8.0, 7.2],
                    [9.0, 4.5],
                    [12.0, 3.5],
                    [15.0, 4.5],
                    [16.0, 7.2],
                    [16.0, 10.5],
                ]),
                Path(&[[12.0, 14.0], [12.0, 17.0]]),
            ],
            Self::Mail => &[
                Path(&[
                    [3.5, 5.5],
                    [20.5, 5.5],
                    [20.5, 18.5],
                    [3.5, 18.5],
                    [3.5, 5.5],
                ]),
                Path(&[[3.5, 6.5], [12.0, 13.0], [20.5, 6.5]]),
            ],
        };
        strokes
            .iter()
            .map(|stroke| match stroke {
                Path(points) => {
                    let closed = points.first() == points.last();
                    let count = points.len() - usize::from(closed);
                    (
                        points[..count]
                            .iter()
                            .map(|p| [p[0] / 24.0, p[1] / 24.0])
                            .collect(),
                        closed,
                    )
                }
                Circle([x, y], radius) => (
                    (0..24)
                        .map(|i| {
                            let angle = i as f32 * std::f32::consts::TAU / 24.0;
                            [
                                (x + angle.cos() * radius) / 24.0,
                                (y + angle.sin() * radius) / 24.0,
                            ]
                        })
                        .collect(),
                    true,
                ),
            })
            .collect()
    }

    pub(super) fn vector_points(self) -> serde_json::Value {
        let (contours, closed): (Vec<_>, Vec<_>) = self.contours().into_iter().unzip();
        paths(&contours, &closed)
    }
}
